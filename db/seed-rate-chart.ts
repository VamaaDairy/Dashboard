async function main() {
  const from = process.argv[2] ?? "2026-10-01";
  if (!/^\d{4}-\d{2}-\d{2}$/.test(from)) throw new Error(`"${from}" is not a date (YYYY-MM-DD)`);
  for (const [fat, rates] of ROWS) {
    if (rates.length !== CLR.length) throw new Error(`fat ${fat}: ${rates.length} rates, expected ${CLR.length}`);
  }

  const client = await pool.connect();
  try {
    const scenario = await client.query<{ id: string }>(
      `select id from scenario order by (status = 'active') desc, created_at desc limit 1`);
    if (!scenario.rows.length) throw new Error("No scenario found - run `npm run db:setup` first");
    const sid = scenario.rows[0].id;

    await client.query("begin");
    await client.query(`delete from milk_rate_grid where scenario_id = $1 and effective_from = $2`, [sid, from]);
    const grid = await client.query<{ id: string }>(
      `insert into milk_rate_grid (scenario_id, name, effective_from, notes)
       values ($1, 'Revised rate chart', $2, '₹ per litre by fat % and CLR - the revised ("39") sheet')
       returning id`,
      [sid, from],
    );
    const values: (string | number)[] = [];
    const tuples: string[] = [];
    for (const [fat, rates] of ROWS) {
      rates.forEach((rate, i) => {
        values.push(grid.rows[0].id, fat, CLR[i], rate);
        const n = values.length;
        tuples.push(`($${n - 3}, $${n - 2}, $${n - 1}, $${n})`);
      });
    }
    await client.query(`insert into milk_rate_grid_cell (grid_id, fat, clr, rate) values ${tuples.join(", ")}`, values);
    await client.query("commit");
    console.log(`loaded revised rate chart: ${tuples.length} rates (fat 3.0-10.0 x CLR 23-30), applies from ${from}`);
  } catch (e) {
    await client.query("rollback");
    throw e;
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
