/**
 * Writes docs/fp-coverage.md: for each of the portal's 184 routes, how it is built here.
 *   npx tsx tools/fp/coverage.ts
 */
import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { ROUTES } from "../../src/lib/fp/model";
import { screenFor } from "../../src/lib/fp/screens";
import { ROW_ACTIONS } from "../../src/lib/fp/rowActions";
import { TABBED } from "../../src/lib/fp/tabs";
import { CONFIGS } from "../../src/lib/fp/configs";
import { OVERRIDES } from "../../src/lib/fp/overrides";

const custom = readFileSync("src/lib/fp/custom.tsx", "utf8");
const isCustom = (k: string) => new RegExp(`routeKey === "${k}"|"${k}"`).test(custom.split("export async function customScreen")[1] ?? "");

const rows: string[] = [];
const count: Record<string, number> = {};
for (const r of ROUTES) {
  const s = screenFor(r.key);
  const tags: string[] = [];
  if (TABBED[r.key]) tags.push(`master lists (${TABBED[r.key].length} tabs)`);
  if (CONFIGS[r.key] || r.key === "pagePermission") tags.push("settings editor");
  if (isCustom(r.key) && !TABBED[r.key]) tags.push("custom screen");
  if (ROW_ACTIONS[r.key]) tags.push(`actions: ${ROW_ACTIONS[r.key].map((a) => a.label).join(", ")}`);
  if (OVERRIDES[r.key]) tags.push("hand-tuned list");
  const noScreen = !s?.cols.length && !tags.length;
  const level = noScreen ? "no data screen" : tags.length ? "built" : "generic list";
  count[level] = (count[level] ?? 0) + 1;
  const total = s?.comp?.gridColumns.length ?? 0;
  rows.push(`| \`/fp/${r.url.replace(/^\//, "")}\` | ${r.title || r.key} | ${level} | ${tags.join("; ") || "-"} | ${s?.table?.entity ?? "-"} | ${s?.cols.length ?? 0}/${total} |`);
}
mkdirSync("docs", { recursive: true });
writeFileSync("docs/fp-coverage.md", [
  "# Field-sales portal - build coverage",
  "",
  "Generated by `tools/fp/coverage.ts` from the spec and the code. Do not edit by hand.",
  "",
  Object.entries(count).map(([k, v]) => `- **${k}**: ${v}`).join("\n"),
  "",
  "- *built*: has its own behaviour (dashboard, workflow actions, document editor, settings editor, master lists or a tuned list).",
  "- *generic list*: the spec's grid read from the real tables (sortable, filterable, CSV); edit form if the spec shows add / update buttons.",
  "- *no data screen*: login / password / single-sign-on pages and shells with no list of their own.",
  "",
  "| Route | Title | Level | What it has | Table | Columns (resolved/spec) |",
  "|---|---|---|---|---|---|",
  ...rows,
].join("\n") + "\n");
console.log(count);
